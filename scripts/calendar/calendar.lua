-- напоминания

local fired = {}
local nextCheck = 0

local function remind(e, text)
    Render.CenteredNotification(text, 6)
    if ui.sound:Get() then pcall(Engine.PlayVol, SOUND, 0.8) end
end

local function checkReminders()
    local now = os.time()
    local before = ui.before:Get() * 60
    for _, day in ipairs({ ymd(now - 86400), ymd(now), ymd(now + 86400) }) do
        for _, p in ipairs(onDay(day)) do
            local e = p.e
            local at = stamp(day, e.time)
            local id = day .. e.time .. e.title
            if before > 0 and now >= at - before and now < at and not fired[id .. "pre"] then
                fired[id .. "pre"] = true
                remind(e, string.format("Через %d мин: %s (%s)", math.ceil((at - now) / 60), e.title, e.time))
            end
            if now >= at and now < at + 120 and not fired[id] then
                fired[id] = true
                remind(e, "Сейчас: " .. e.title)
            end
        end
    end
end

function script.OnUpdateEx()
    if not ui.on or not ui.on:Get() then
        view.open = false
        return
    end
    if ui.open:IsPressed() then view.open = not view.open end
    if os.clock() >= nextCheck then
        nextCheck = os.clock() + 1
        checkReminders()
    end
end

-- окно

local font = nil
local frameAt = -10
local click = false
local panel = { w = CELL * 7 + 24, h = 0 }
local hits = {}

local function col(r, g, b, a) return Color(r, g, b, a or 255) end

local function text(s, x, y, size, c) Render.Text(font, size, s, Vec2(x, y), c) end

local function centered(s, x, w, y, size, c)
    local tw = Render.TextSize(font, size, s).x
    text(s, x + (w - tw) / 2, y, size, c)
end

local function hit(x, y, w, h, action) hits[#hits + 1] = { x = x, y = y, w = w, h = h, action = action } end

local function shiftMonth(delta)
    view.month = view.month + delta
    if view.month < 1 then view.month, view.year = 12, view.year - 1 end
    if view.month > 12 then view.month, view.year = 1, view.year + 1 end
end

local function drawPanel()
    hits = {}
    local x, y, w = PANEL_X, PANEL_Y, panel.w
    local list = onDay(view.day)
    local first = os.date("*t", os.time({ year = view.year, month = view.month, day = 1, hour = 12 }))
    local offset = (first.wday + 5) % 7
    local days = os.date("*t", os.time({ year = view.year, month = view.month + 1, day = 0, hour = 12 })).day
    local weeks = math.ceil((offset + days) / 7)
    local h = HEAD + weeks * CELL + 34 + math.max(1, #list) * ROW + 30
    panel.h = h

    Render.FilledRect(Vec2(x, y), Vec2(x + w, y + h), col(22, 26, 34, 238), 10)
    Render.Rect(Vec2(x, y), Vec2(x + w, y + h), col(90, 110, 140, 200), 10)

    centered(MONTHS[view.month] .. " " .. view.year, x, w, y + 12, 18, col(235, 240, 250))
    text("<", x + 16, y + 10, 20, col(170, 190, 220))
    text(">", x + w - 28, y + 10, 20, col(170, 190, 220))
    hit(x, y + 4, 50, 34, function() shiftMonth(-1) end)
    hit(x + w - 50, y + 4, 50, 34, function() shiftMonth(1) end)

    for i, wd in ipairs(WEEK) do
        centered(wd, x + 12 + (i - 1) * CELL, CELL, y + 46, 13, i >= 6 and col(240, 150, 140) or col(150, 165, 190))
    end

    local today = ymd()
    for d = 1, days do
        local idx = offset + d - 1
        local cx, cy = x + 12 + (idx % 7) * CELL, y + HEAD + (idx // 7) * CELL
        local day = string.format("%04d-%02d-%02d", view.year, view.month, d)
        if day == view.day then
            Render.FilledRect(Vec2(cx + 3, cy + 3), Vec2(cx + CELL - 3, cy + CELL - 3), col(70, 95, 140, 220), 6)
        end
        if day == today then
            Render.Rect(Vec2(cx + 3, cy + 3), Vec2(cx + CELL - 3, cy + CELL - 3), col(255, 200, 90), 6, nil, 2)
        end
        centered(tostring(d), cx, CELL, cy + 10, 15, day < today and col(120, 130, 150) or col(230, 235, 245))
        local n = #onDay(day)
        if n > 0 then
            for k = 1, math.min(n, 3) do
                Render.FilledCircle(Vec2(cx + CELL / 2 + (k - (math.min(n, 3) + 1) / 2) * 7, cy + CELL - 9), 2.5, col(120, 220, 140))
            end
        end
        hit(cx, cy, CELL, CELL, function() view.day = day end)
    end

    local ly = y + HEAD + weeks * CELL + 8
    text(string.format("%s.%s", view.day:sub(9, 10), view.day:sub(6, 7)), x + 14, ly, 15, col(200, 210, 230))
    ly = ly + 24
    if #list == 0 then
        text("Событий нет", x + 14, ly, 14, col(130, 140, 160))
        ly = ly + ROW
    end
    for _, p in ipairs(list) do
        local e = p.e
        local rep = e.rep > 0 and ("  (" .. REPEATS[e.rep + 1]:lower() .. ")") or ""
        text(e.time .. "  " .. e.title .. rep, x + 14, ly, 14, col(230, 235, 245))
        text("x", x + w - 24, ly - 1, 15, col(240, 120, 110))
        local index = p.i
        hit(x + w - 34, ly - 3, 30, ROW, function()
            table.remove(events, index)
            save()
        end)
        ly = ly + ROW
    end
    text("Клик - выбрать день, < > - месяц, End - закрыть", x + 14, ly + 6, 12, col(120, 130, 150))
    return x, y
end

function script.OnFrame()
    if not ui.on or not ui.on:Get() or not view.open then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 500) end
    drawPanel()
    frameAt = os.clock()

    local pressed = click
    click = false
    if not Engine.IsInGame() then pressed = Input.IsKeyDownOnce(Enum.ButtonCode.KEY_MOUSE1, true) end
    if not pressed then return end
    for i = #hits, 1, -1 do
        local hb = hits[i]
        if Input.IsCursorInRect(hb.x, hb.y, hb.w, hb.h) then
            hb.action()
            break
        end
    end
end

function script.OnKeyEvent(data)
    if not view.open or type(data) ~= "table" then return true end
    if os.clock() - frameAt > GRACE or Menu.Opened() then return true end
    if data.event ~= Enum.EKeyEvent.EKeyEvent_KEY_DOWN then return true end
    if data.key == Enum.ButtonCode.KEY_END then
        view.open = false
        return false
    end
    if data.key == Enum.ButtonCode.KEY_MOUSE1 and Engine.IsInGame() and Input.IsCursorInRect(PANEL_X, PANEL_Y, panel.w, panel.h) then
        click = true
        return false
    end
    return true
end

return script


