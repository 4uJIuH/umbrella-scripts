    local date = parseDate(ui.date:Get())
    local time = parseTime(ui.time:Get())
    if title == "" then return Render.CenteredNotification("Календарь: впиши название события", 3) end
    if not date then return Render.CenteredNotification("Календарь: дата как 25.10, 25.10.2026, сегодня или завтра", 4) end
    if not time then return Render.CenteredNotification("Календарь: время как 19:30 или 19", 4) end
    if #events >= MAX_EVENTS then return Render.CenteredNotification("Календарь: слишком много событий, удали старые", 4) end
    events[#events + 1] = { date = date, time = time, rep = ui.rep:Get(), title = title }
    save()
    ui.title:Set("")
    view.day = date
    view.year, view.month = tonumber(date:sub(1, 4)), tonumber(date:sub(6, 7))
    view.open = true
    Render.CenteredNotification("Добавлено: " .. title .. ", " .. date:sub(9, 10) .. "." .. date:sub(6, 7) .. " в " .. time, 3)
end

