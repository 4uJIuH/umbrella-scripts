-- события

local events = {}

local function save()
    local parts = {}
    for _, e in ipairs(events) do
        parts[#parts + 1] = table.concat({ e.date, e.time, e.rep, e.title }, "^")
    end
    Config.WriteString(CFG, "events", table.concat(parts, "~"))
end

local function load()
    events = {}
    for rec in (Config.ReadString(CFG, "events", "") or ""):gmatch("[^~]+") do
        local date, time, rep, title = rec:match("^([^%^]*)%^([^%^]*)%^([^%^]*)%^(.*)$")
        if date then events[#events + 1] = { date = date, time = time, rep = tonumber(rep) or 0, title = title } end
    end
end

local function ymd(t) return os.date("%Y-%m-%d", t) end

local function stamp(date, time)
    local y, m, d = date:match("^(%d+)-(%d+)-(%d+)$")
    local hh, mm = (time or ""):match("^(%d+):(%d+)$")
    return os.time({ year = tonumber(y), month = tonumber(m), day = tonumber(d), hour = tonumber(hh) or 0, min = tonumber(mm) or 0, sec = 0 })
end

local function occurs(e, day)
    if day < e.date then return false end
    if e.rep == 0 then return day == e.date end
    if e.rep == 1 then return true end
    local a, b = os.date("*t", stamp(e.date)), os.date("*t", stamp(day))
    if e.rep == 2 then return a.wday == b.wday end
    return a.day == b.day
end

local function onDay(day)
    local out = {}
    for i, e in ipairs(events) do
        if occurs(e, day) then out[#out + 1] = { e = e, i = i } end
    end
    table.sort(out, function(p, q) return p.e.time < q.e.time end)
    return out
end

-- меню

local ui = {}
local view = { open = false, year = 0, month = 0, day = ymd() }

local function parseDate(s)
    s = (s or ""):lower():match("^%s*(.-)%s*$")
    if s == "" or s == "сегодня" then return ymd() end
    if s == "завтра" then return ymd(os.time() + 86400) end
    if s == "послезавтра" then return ymd(os.time() + 2 * 86400) end
    local d, m, y = s:match("^(%d+)%.(%d+)%.?(%d*)$")
    if not d then return nil end
    y = tonumber(y) or tonumber(os.date("%Y"))
    if y < 100 then y = y + 2000 end
    d, m = tonumber(d), tonumber(m)
    if m < 1 or m > 12 or d < 1 or d > 31 then return nil end
    local t = os.time({ year = y, month = m, day = d, hour = 12 })
    if os.date("*t", t).day ~= d then return nil end
    return ymd(t)
end

local function parseTime(s)
    s = (s or ""):match("^%s*(.-)%s*$")
    if s == "" then return "00:00" end
    local h, m = s:match("^(%d+)[:%.](%d+)$")
    if not h then h, m = s:match("^(%d+)$"), "0" end
    h, m = tonumber(h), tonumber(m)
    if not h or h > 23 or m > 59 then return nil end
    return string.format("%02d:%02d", h, m)
end

