            local name = Ability.GetName(item)
            if FOOD[name] then
                local c = math.max(1, Item.GetCurrentCharges(item) or 0)
                local e = counts[name] or { n = 0, cd = false }
                e.n = e.n + c
                if (Ability.GetCooldown(item) or 0) > 0 then e.cd = true end
                counts[name] = e
            end
        end
    end
    return counts
end

local function eat(name, times)
    local food = FOOD[name]
    local kcal = food[2] * times
    game.eaten = game.eaten + kcal
    if not game.menu[food[1]] then
        game.menu[food[1]] = { n = 0, kcal = 0 }
        game.order[#game.order + 1] = food[1]
    end
    local m = game.menu[food[1]]
    m.n, m.kcal = m.n + times, m.kcal + kcal
    pops[#pops + 1] = { text = string.format("+%d ккал (%s)", kcal, food[1]), till = os.clock() + POP_TIME }
    Config.WriteFloat(CFG, "total", Config.ReadFloat(CFG, "total", 0) + kcal)
end

local function verdict(balance)
    for _, v in ipairs(VERDICTS) do
        if balance > v[1] then return v[2] end
    end
    return VERDICTS[#VERDICTS][2]
end

local function showSummary()
    if not game then return end
    local burn = math.floor(burned())
    local balance = game.eaten - burn - ui.norm:Get()
    local lines = { string.format("Съедено %d ккал, сожжено %d, норма %d", game.eaten, burn, ui.norm:Get()) }
    for _, name in ipairs(game.order) do
        local m = game.menu[name]
        lines[#lines + 1] = string.format("%s x%d - %d ккал", name, m.n, m.kcal)
    end
    if #game.order == 0 then lines[#lines + 1] = "Герой за игру ничего не съел" end
    lines[#lines + 1] = verdict(balance)
    lines[#lines + 1] = string.format("За всё время: %d ккал", math.floor(Config.ReadFloat(CFG, "total", 0)))
    summary = { lines = lines, till = os.clock() + SHOW_SECONDS }
end

function script.OnUpdate()
    if not ui.on or not ui.on:Get() then return end
    local h = Heroes.GetLocal()
    if not h then return end
    if h ~= hero then newGame(h) end
    if ui.show:IsPressed() then showSummary() end

    local now = os.clock()
    local pos = Entity.GetAbsOrigin(h)
    if Entity.IsAlive(h) and game.last then
        local d = (pos - game.last):Length2D()
        if d < JUMP then game.run = game.run + d end
    end
    game.last = Entity.IsAlive(h) and pos or nil

    if now - game.scan < SCAN_EVERY then return end
    game.scan = now
    local counts = inventory(h)
    if game.counts then
        for name, before in pairs(game.counts) do
            local after = counts[name]
            local left = after and after.n or 0
            if left < before.n and (not after or after.cd) then eat(name, before.n - left) end
        end
    end
    game.counts = counts
end

function script.OnGameEnd()
    if not game then return end
    showSummary()
    if ui.brag:Get() then
        local text = string.format("Мой герой за игру съел %d ккал и сжёг %d. %s", game.eaten, math.floor(burned()),
            verdict(game.eaten - burned() - ui.norm:Get()))
        pcall(Chat.Say, ALLIES, text)
    end
end

-- рисуем

local font = nil

local function text(s, x, y, size, c)
    Render.Text(font, size, s, Vec2(x + 1, y + 1), Color(0, 0, 0, 200))
    Render.Text(font, size, s, Vec2(x, y), c)
end

function script.OnDraw()
    if not ui.on or not ui.on:Get() or not game then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 500) end
    local now = os.clock()

    if ui.hud:Get() then
        local burn = math.floor(burned())
        local balance = game.eaten - burn
        text(string.format("Калории: съедено %d · сожжено %d · баланс %+d", game.eaten, burn, balance), 20, 140, 14, Color(255, 215, 150, 230))
    end

    if ui.pop:Get() and hero then
        local p, visible = Render.WorldToScreen(Entity.GetAbsOrigin(hero) + Vector(0, 0, 250))
        local k = 0
        for i = #pops, 1, -1 do
            local pop = pops[i]
            if now > pop.till then
                table.remove(pops, i)
            elseif visible then
                local rise = (1 - (pop.till - now) / POP_TIME) * 40
                local w = Render.TextSize(font, 16, pop.text).x
                text(pop.text, p.x - w / 2, p.y - rise - k * 20, 16, Color(140, 240, 120, 240))
                k = k + 1
            end
        end
    end

    if summary and now < summary.till then
        local s = Render.ScreenSize()
        local y = s.y * 0.26
        for i, l in ipairs(summary.lines) do
            local size = i == 1 and 18 or 15
            local w = Render.TextSize(font, size, l).x
            text(l, (s.x - w) / 2, y, size, i == #summary.lines - 1 and Color(255, 200, 120) or Color(235, 240, 235))
            y = y + size + 7
        end
    end
end

return script


