local game = nil
local hero = nil
local pops = {}
local summary = nil

local function newGame(h)
    hero = h
    game = { eaten = 0, run = 0, start = os.clock(), menu = {}, order = {}, counts = nil, last = nil, scan = 0 }
end

local function burned()
    local minutes = (os.clock() - game.start) / 60
    return game.run * CM_PER_UNIT / 100 / 1000 * KCAL_PER_KM + minutes * KCAL_PER_MIN
end

