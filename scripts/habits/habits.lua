-- хранилище

local function today() return os.date("%Y-%m-%d") end
local function yesterday() return os.date("%Y-%m-%d", os.time() - 86400) end

local function key(prefix, name)
    local hex = name:sub(1, 30):gsub(".", function(c) return string.format("%02x", c:byte()) end)
    return prefix .. hex
end

local function habits()
    local out = {}
    for raw in (ui.list:Get() or ""):gmatch("[^,]+") do
        local name = raw:match("^%s*(.-)%s*$")
        if name ~= "" and #out < MAX_HABITS then out[#out + 1] = name end
    end
    return out
end

local function lifeState(name)
    local last = Config.ReadString(CFG, key("ld", name), "")
    local streak = Config.ReadInt(CFG, key("ls", name), 0)
    local done = last == today()
    if last ~= today() and last ~= yesterday() then streak = 0 end
    return done, streak
end

local function toggleLife(name)
    local kd, ks, kq, kp = key("ld", name), key("ls", name), key("lq", name), key("lp", name)
    local last = Config.ReadString(CFG, kd, "")
    if last == today() then
        Config.WriteString(CFG, kd, Config.ReadString(CFG, kq, ""))
        Config.WriteInt(CFG, ks, Config.ReadInt(CFG, kp, 0))
        return
    end
    local streak = Config.ReadInt(CFG, ks, 0)
    Config.WriteString(CFG, kq, last)
    Config.WriteInt(CFG, kp, streak)
    Config.WriteInt(CFG, ks, last == yesterday() and streak + 1 or 1)
    Config.WriteString(CFG, kd, today())
end

local function pending()
    local left = {}
    for _, name in ipairs(habits()) do
        if not lifeState(name) then left[#left + 1] = name end
    end
    return left
end

-- игра

local game = nil
local hero = nil

local function newGame(h)
    hero = h
    game = { wards = false, deny = 0, diedEarly = false, idle = 0, longest = 0, last = nil, tick = 0, done = false }
end

local function verdict(id)
    if id == "wards" then return game.wards end
    if id == "deny" then return game.deny >= DENY_GOAL end
    if id == "alive" then return not game.diedEarly end
    return game.idle <= IDLE_LIMIT
end

local function progress(id)
    if id == "wards" then return game.wards and "куплены" or "ещё нет" end
    if id == "deny" then return game.deny .. "/" .. DENY_GOAL end
    if id == "alive" then return game.diedEarly and "умер" or "жив" end
    return string.format("%d/%d с", math.floor(game.idle), IDLE_LIMIT)
end

local summary = nil

local function finishGame()
    if not game or game.done then return end
    game.done = true
    if GameRules.GetDOTATime() < MIN_GAME then return end
    local lines, passed = {}, 0
    for _, g in ipairs(GAME_HABITS) do
        local ok = verdict(g.id)
        local s = Config.ReadInt(CFG, "gs_" .. g.id, 0)
        s = ok and s + 1 or 0
        Config.WriteInt(CFG, "gs_" .. g.id, s)
        Config.WriteInt(CFG, "gr_" .. g.id, ok and 1 or 2)
        if ok then passed = passed + 1 end
        lines[#lines + 1] = (ok and "+ " or "- ") .. g.name .. (ok and ("  (серия " .. s .. ")") or "  (серия сброшена)")
    end
    Config.WriteInt(CFG, "games", Config.ReadInt(CFG, "games", 0) + 1)
    table.insert(lines, 1, string.format("Игровые привычки: %d из %d", passed, #GAME_HABITS))
    local left = pending()
    if #left > 0 then lines[#lines + 1] = "А ещё сегодня не отмечено: " .. table.concat(left, ", ") end
    summary = { lines = lines, till = os.clock() + 12 }
end

local function hasWard(h)
    return NPC.HasItem(h, "item_ward_observer") or NPC.HasItem(h, "item_ward_sentry") or NPC.HasItem(h, "item_ward_dispenser")
end

function script.OnEntityKilled(data)
    if not game or not hero or type(data) ~= "table" or not data.target then return end
    if data.target == hero then
        if GameRules.GetDOTATime() < EARLY_DEATH then game.diedEarly = true end
    elseif data.source == hero and not Entity.IsHero(data.target) and Entity.GetTeamNum(data.target) == Entity.GetTeamNum(hero) then
        game.deny = game.deny + 1
    end
end

function script.OnGameEnd()
    finishGame()
end

local lastRemind = nil

function script.OnUpdate()
    if not ui.on or not ui.on:Get() or not ui.game:Get() then return end
    local h = Heroes.GetLocal()
    if not h then return end
    if h ~= hero then
        finishGame()
        newGame(h)
    end

    local now = os.clock()
    if now - game.tick < 1 then return end
    local dt = game.tick > 0 and math.min(2, now - game.tick) or 0
    game.tick = now

    if not game.wards and hasWard(h) then game.wards = true end

    local pos = Entity.GetAbsOrigin(h)
    if Entity.IsAlive(h) and GameRules.GetDOTATime() > 0 and game.last and (pos - game.last):Length2D() < IDLE_MOVE then
        game.idle = game.idle + dt
    end
    game.last = pos
end

-- окно

local open = false
local panelH = 0
local frameAt = -10
local click = false
local rows = {}
local font = nil

local function col(r, g, b, a) return Color(r, g, b, a or 255) end

local function text(s, x, y, size, c)
    Render.Text(font, size, s, Vec2(x, y), c)
end

local function drawPanel()
    local list = habits()
    local gameRows = (ui.game:Get() and game) and #GAME_HABITS + 1 or 0
    local h = ROW * (#list + gameRows + 3) + 20
    local x, y = PANEL_X, PANEL_Y
    Render.FilledRect(Vec2(x, y), Vec2(x + PANEL_W, y + h), col(22, 26, 34, 235), 10)
    Render.Rect(Vec2(x, y), Vec2(x + PANEL_W, y + h), col(90, 110, 140, 200), 10)

    rows = {}
    local cy = y + 10
    text("Привычки на " .. os.date("%d.%m"), x + 14, cy, 17, col(235, 240, 250))
    cy = cy + ROW + 4

    for _, name in ipairs(list) do
        local done, streak = lifeState(name)
        local box = Vec2(x + 14, cy + 3)
        Render.Rect(box, Vec2(box.x + 16, box.y + 16), col(160, 180, 210), 3, nil, 2)
        if done then Render.FilledRect(Vec2(box.x + 4, box.y + 4), Vec2(box.x + 12, box.y + 12), col(110, 220, 120), 2) end
        text(name, x + 42, cy + 2, 15, done and col(150, 160, 175) or col(230, 235, 245))
        if streak > 0 then
            local s = "серия " .. streak .. " дн"
            text(s, x + PANEL_W - 14 - Render.TextSize(font, 13, s).x, cy + 4, 13, col(255, 190, 90))
        end
        rows[#rows + 1] = { y = cy, name = name }
        cy = cy + ROW
    end
    if #list == 0 then
        text("Впиши привычки в меню скрипта", x + 14, cy + 2, 14, col(160, 170, 185))
        cy = cy + ROW
    end

    if gameRows > 0 then
        cy = cy + 6
        text("Эта игра", x + 14, cy, 15, col(200, 210, 230))
        cy = cy + ROW
        for _, g in ipairs(GAME_HABITS) do
            local ok = verdict(g.id)
            text(g.name, x + 14, cy + 2, 14, col(220, 225, 235))
            local s = progress(g.id) .. "  |  серия " .. Config.ReadInt(CFG, "gs_" .. g.id, 0)
            text(s, x + PANEL_W - 14 - Render.TextSize(font, 13, s).x, cy + 4, 13, ok and col(120, 220, 130) or col(230, 170, 120))
            cy = cy + ROW
        end
    end

    text("Клик - отметить, End - закрыть", x + 14, cy + 6, 12, col(120, 130, 150))
    return x, y, h
end

local function drawSummary()
    local s = Render.ScreenSize()
    local y = s.y * 0.28
    for i, l in ipairs(summary.lines) do
        local size = i == 1 and 19 or 15
        local w = Render.TextSize(font, size, l).x
        text(l, (s.x - w) / 2 + 1, y + 1, size, col(0, 0, 0, 200))
        text(l, (s.x - w) / 2, y, size, l:sub(1, 1) == "-" and col(240, 160, 120) or col(235, 245, 235))
        y = y + size + 8
    end
end

function script.OnUpdateEx()
    if not ui.on or not ui.on:Get() then
        open = false
        return
    end
    if ui.open:IsPressed() then open = not open end

    local every = ui.remind:Get()
    if every > 0 and Engine.IsInGame() then
        local now = os.clock()
        lastRemind = lastRemind or now
        if now - lastRemind > every * 60 then
            lastRemind = now
            local left = pending()
            if #left > 0 then Render.CenteredNotification("Не забудь: " .. table.concat(left, ", "), 5) end
        end
    end
end

function script.OnFrame()
    if not ui.on or not ui.on:Get() then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 500) end

    if summary and os.clock() < summary.till then drawSummary() end
    if not open then return end

    local x, y, h = drawPanel()
    panelH = h
    frameAt = os.clock()

    local hit = click
    if not Engine.IsInGame() then hit = Input.IsKeyDownOnce(Enum.ButtonCode.KEY_MOUSE1, true) end
    click = false
    if not hit then return end
    for _, r in ipairs(rows) do
        if Input.IsCursorInRect(x, r.y, PANEL_W, ROW) then
            toggleLife(r.name)
            break
        end
    end
end

function script.OnKeyEvent(data)
    if not open or type(data) ~= "table" then return true end
    if os.clock() - frameAt > GRACE or Menu.Opened() then return true end
    if data.event ~= Enum.EKeyEvent.EKeyEvent_KEY_DOWN then return true end
    if data.key == Enum.ButtonCode.KEY_END then
        open = false
        return false
    end
    if data.key == Enum.ButtonCode.KEY_MOUSE1 and Engine.IsInGame() and Input.IsCursorInRect(PANEL_X, PANEL_Y, PANEL_W, panelH) then
        click = true
        return false
    end
    return true
end

return script


